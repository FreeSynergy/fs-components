"""Writer of TOKENS.md from the data tree of `tokens.build`. Pattern: Template method (fixed sections, tables filled from the data)."""
from __future__ import annotations

from collections import Counter

from .tokenscale import LADDER, ladder_name

STYLES = ("craft", "admin", "apple", "simple", "windows")
CLASSES = ("scope", "last-wave", "style-definition", "icon-content")
CMD = "python3 -I contract/umbau/tokens --write contract/umbau"


def g(x):
    return f"{x:g}"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def places(e):
    c = e["classes"]
    return " / ".join(str(c.get(k, 0)) for k in CLASSES)


def target(e):
    if e["status"] in ("scale", "new"):
        return f"`{e['token'][0]}` ({g(e['step'])}){' NEW' if e['status'] == 'new' else ''}"
    if e["status"] == "role":
        return f"`{e['token'][0]}` (by role, {g(e['dev'])} {'/255' if e['kind'] == 'color' else 'px'} off) CHANGE"
    if e["status"] == "none":
        return "nothing set (zero, opacity 1): not counted any more"
    if e["status"] == "own-style":
        return "no step within tolerance: last wave moves into styles, sheet values stay" if set(e["classes"]) <= {"last-wave", "style-definition"} else "NEW token needed"
    if e["kind"] == "color":
        if e["token"]:
            return f"`{e['token'][0]}`"
        c = e["classes"]
        return "NEW token" if c.get("scope") else "last wave: own style" if c.get("last-wave") else "content (drawn icon)" if c.get("icon-content") else "style definition"
    return "exception"


def scale_rows(data, kind):
    rows = []
    for token, per in data["scales"][kind]["values"].items():
        if ".step." in token:
            continue
        rows.append([f"`{token}`"] + [g(per[s]) if s in per else "-" for s in STYLES] + [data["scales"][kind]["where"][token].get("craft", "-").replace("crates/fs-components-styles/src/styles/", "")])
    rows += [[f"`{n['token']}` NEW", g(n["value"]), "= craft [offen]", "= craft [offen]", "= craft [offen]", "= craft [offen]", "new"] for n in data["scales"][kind]["new"]]
    return rows


def build(data):
    nc, lits = data["new_count"], data["literals"]
    total = sum(nc["scope"].values())
    out = ["# Tokens: scales, assignment of every counted literal, new tokens (ADR 0074)", "",
           f"Generated by `{CMD}` from `start.json` (the totals are checked against it) and the style definitions. Do not edit. Nothing is converted yet; "
           "no file under `crates/` was changed. What is not proven is marked **[offen]**.", "", "## 0. Result", "",
           f"- **New tokens needed: {total}**: spacing {nc['scope']['spacing']}, border {nc['scope']['border']}, size {nc['scope']['size']}, opacity {nc['scope']['opacity']}, "
           f"radius {nc['scope']['radius']}, colour {nc['scope']['color']}, font {nc['scope']['font']}, shadow 0 (only the places converted now; ZUORDNUNG proposed 105 values 1:1).",
           f"- The last wave (wiki frontends `workbenches/view`, `widgets/plan`) is not counted: its values move into styles (strategy 5). On the same scales it would add "
           f"{sum(nc['with_last_wave'].values()) - total} more (spacing {nc['with_last_wave']['spacing']}, size {nc['with_last_wave']['size']}, font {nc['with_last_wave']['font']}, "
           f"opacity {nc['with_last_wave']['opacity']}, colour {nc['with_last_wave']['color']}). Tolerance 4 px instead of 2 would give size {nc['tolerance_4']['size']} instead of {nc['scope']['size']}: rejected (16 to 20 px is 25 percent).",
           "- **Deliberate picture changes** (a role instead of a value, listed so the comparison expects them): `badge.rs:41` and `search_field/field.rs:106` get `radius.control` (Craft: 0; was 5 and 6 px); "
           "file manager `#e3e3e3` becomes `color.border.line` (24/255) and `#f7f7f8` becomes `color.surface.panel` (10/255); every other deviation is in section 5.", "",
           "Where the counted places go (columns: in scope now / last wave / style definition / drawn icon / sets nothing):", ""]
    rows, tot = [], Counter()
    for kind in sorted({e["kind"] for e in lits}):
        c = Counter()
        for e in lits:
            if e["kind"] == kind:
                for k, n in e["classes"].items():
                    c["none" if e["status"] == "none" and k in ("scope", "last-wave") else k] += n
        rows.append([kind] + [c.get(k, 0) for k in CLASSES + ("none",)] + [sum(c.values())])
        tot.update(c)
    rows.append(["**all**"] + [tot.get(k, 0) for k in CLASSES + ("none",)] + [sum(tot.values())])
    out += table(["kind", "scope", "last wave", "style definition", "drawn icon", "sets nothing", "total"], rows) + [""]
    out += [f"Counted now (`count`, `start.json`): scope + last wave = {sum(data['counted'].values())} places. Left out of the count: style definition and drawn icon (`[fixed-values]` in `exceptions.toml`, section 6) and values that set nothing "
            "(zero spacing, size, radius, border; `opacity: 1`): `count` skips them (probe in `umbau/selftest`).", "",
            "## 1. Rules used", "",
            "1. **Reference style Craft** (strategy 1): a literal is compared with the Craft value of a token; the other four styles keep their own values (for NEW tokens vorerst the Craft value, per style **[offen]**).",
            "2. **A scale per kind from the tokens that exist**, including the ladder that `fs-components-render/src/style_theme.rs` derives for Blinc (the code reads `--space-*`, `--radius-*`, `--text-*` about 400 times): `space.*` + the ladder, `size.*` + `icon.size` + the two line widths, `font.size.*` + `font.size.xl`, `radius.*` (roles). Border width and opacity had no token. Colours: equal to a token, or a role.",
            "3. **Fit:** equal, or at most **2 px** off (opacity 0.05, **[offen]** unit) and, **below 4 px, at most half of the smaller of the two values** (precision of the 2 px rule, accepted in the review: without it 63 hairlines would double). Tie: the smaller step; at equal value a role token before a ladder step.",
            "4. **A step is NEW** only when none fits; greedy: most places reached, then least total deviation, then smaller. The three border roles are fixed by role. Radius and colour are placed **by role**, not by nearest value (review b, d).",
            "5. Not mapped now: style definition, drawn icon, last wave (shown against the scale for information only).", "",
            "## 2. The scales (Craft first; source = definition line)", ""]
    for kind, title in (("spacing", "space"), ("size", "size (and icon.size)"), ("font", "font size"), ("radius", "radius (roles)"), ("border", "border width"), ("opacity", "opacity")):
        out += [f"**{title}** ({kind}, px{', 0..1' if kind == 'opacity' else ''})", ""] + table(["token", *STYLES, "source"], scale_rows(data, kind)) + [""]
    xs = data["scales"]["spacing"]["values"]
    out += ["**The bridge** (what Blinc reads; all derived from the style, so every style has the same names): "
            "`space.step.<k>` = `space.xs` x k for k in " + ", ".join(f"{k:g}" for k in LADDER) + "; Blinc variable `--space-<k>` with `.` written `_` (`space.step.1-5` is `--space-1_5`). "
            "Craft (xs 4): " + ", ".join(g(xs[ladder_name(k)]["craft"]) for k in LADDER) + " px; Simple (xs 8) doubles them. Source `style_theme.rs`, `blinc_theme 0.6.0 tokens/spacing.rs:90-115`. "
            "Radius: `--radius-sm`, `--radius-default` = `radius.control`; `-md`, `-lg` = `radius.card`; `-xl` to `-3xl` = `radius.overlay`; `-none` = 0. "
            "Text: `--text-xs` = `font.size.caption`; `-sm`, `-base` = `font.size.body`; `-lg` = `font.size.title`; `-xl` = `font.size.xl` (title + 2); `-2xl` = `font.size.headline`.", "",
            "Craft has square corners (`radius.* = 0`, test `the_sheet_has_no_rounded_corner`), so no radius literal sits on a Craft step. "
            "Craft defines no border or opacity token (only sheet literals `1px`, `0.4`); `border.focus.width` 2/3/4 of the other styles is a focus ring, not a line width.", "",
            "## 3. New tokens (names after DTCG: lower-case dot path, kebab segments; proposals, roles read from the places of use)", ""]
    rows = []
    for kind in ("spacing", "border", "size", "opacity"):
        for n in data["scales"][kind]["new"]:
            cover = [e for e in lits if e["kind"] == kind and e.get("token") == [n["token"]] and e["classes"].get("scope")]
            rows.append([f"`{n['token']}`", kind, g(n["value"]), ", ".join(e["value"] for e in cover), sum(e["classes"]["scope"] for e in cover)])
    out += table(["token", "kind", "Craft value", "covers (literals in scope)", "scope places"], rows) + [""]
    out += ["`border.width.indicator` (4) is the left bar of `agent_tree/styles.rs:10`; `border.width.strong` (2) takes the two 3 px bars (calendar item, text_view quote) down to 2. "
            "The wide sizes (`size.dialog-max` 560, `size.col-s/-m` 96/120, `size.col-narrow` 72, `size.row-tall(er)` 56/60, `size.field-tall` 64) are single layout measures kept as tokens because the strategy forbids a literal. "
            "`space.px` (1) is an integer hairline gap (5 places; 1.5 also lands there by the tie rule).", ""]
    out += ["## 4. Every counted literal and where it goes", "", "Places in brackets: scope / last wave / style definition / drawn icon; dev in px (opacity absolute, colour in /255).", ""]
    for kind in ("spacing", "size", "font", "radius", "border", "opacity", "color", "shadow"):
        groups = {}
        for e in lits:
            if e["kind"] == kind:
                cell = f"`{e['value']}` ({places(e)}{'; dev ' + g(e['dev']) if e.get('dev') else ''})"
                groups.setdefault(target(e), []).append(cell)
        out += [f"**{kind}**", ""] + table(["target", "literals (places; deviation)"], [[t, ", ".join(c)] for t, c in groups.items()]) + [""]
    out += ["## 5. Deviations in scope (literal != step): the tolerance list of the picture comparison", "",
            "Per group in `tokens.json` (`tolerance_list`: kind, literal, token, dev, place, deliberate). Every place may differ by `dev` in the Craft picture; `CHANGE` rows are deliberate.", ""]
    rows = []
    for e in lits:
        sites = e.get("sites", {}).get("scope")
        if sites:
            rows.append([e["kind"], f"`{e['value']}`", f"`{e['token'][0]}`", g(e["dev"]), len(sites), "CHANGE" if e.get("deliberate") else "", "; ".join(x.replace("crates/fs-components-", "").replace("/src", "") for x in sites[:2]) + (" ..." if len(sites) > 2 else "")])
    out += table(["kind", "literal", "token", "dev", "places", "", "first places"], rows) + [""]
    groups = data["tolerance_list"]
    out += ["Places per group: " + ", ".join(f"{k.replace('fs-components-', '')} {len(v)}" for k, v in groups.items()) + ".", ""]
    lw = [e for e in lits if e.get("sites", {}).get("last-wave")]
    out += [f"Last wave: {sum(len(e['sites']['last-wave']) for e in lw)} further deviating places (they move into styles, no tolerance).", ""]
    return out
