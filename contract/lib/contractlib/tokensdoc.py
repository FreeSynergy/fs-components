"""Writer of TOKENS.md from the data tree of `tokens.build`. Pattern: Template method (fixed sections, tables filled from the data)."""
from __future__ import annotations

from collections import Counter

STYLES = ("craft", "admin", "apple", "simple", "windows")
CLASSES = ("scope", "last-wave", "style-definition", "icon-content")
CMD = "python3 -I contract/umbau/tokens --write contract/umbau"


def g(x):
    return f"{x:g}"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def places(e):
    c = e["classes"]
    return " / ".join(str(c.get(k, 0)) for k in CLASSES)


def target(e):
    if e["status"] in ("scale", "new"):
        return f"`{e['token'][0]}` ({g(e['step'])}){' NEW' if e['status'] == 'new' else ''}"
    if e["status"] == "none":
        return "none (zero or opacity 1: remove the declaration)"
    if e["status"] == "own-style":
        return "no step within tolerance: last wave moves into styles, sheet values stay" if set(e["classes"]) <= {"last-wave", "style-definition"} else "NEW token needed"
    if e["kind"] == "color":
        if e["token"]:
            return f"`{e['token'][0]}`"
        c = e["classes"]
        return "NEW token" if c.get("scope") else "last wave: own style" if c.get("last-wave") else "content (drawn icon)" if c.get("icon-content") else "style definition"
    return "exception"


def scale_rows(data, kind):
    rows = []
    for token, per in data["scales"][kind]["values"].items():
        rows.append([f"`{token}`"] + [g(per[s]) if s in per else "-" for s in STYLES] + [data["scales"][kind]["where"][token].get("craft", "-").replace("crates/fs-components-styles/src/styles/", "")])
    rows += [[f"`{n['token']}` NEW", g(n["value"]), "[offen]", "[offen]", "[offen]", "[offen]", "new"] for n in data["scales"][kind]["new"]]
    return rows


def build(data):
    nc, lits = data["new_count"], data["literals"]

    def zero(kind):
        return sum(e["classes"].get("scope", 0) for e in lits if e["kind"] == kind and e["status"] == "none")

    total = sum(nc["scope"].values())
    out = ["# Tokens: scales, assignment of every counted literal, new tokens (ADR 0074)", "",
           f"Generated by `{CMD}` from `start.json` (totals are checked against it) and the style definitions. Do not edit. Nothing here is converted yet; "
           "no file under `crates/` was changed. What is not proven is marked **[offen]**.", "", "## 0. Result", "",
           f"- **New tokens needed: {total}** (spacing {nc['scope']['spacing']}, border {nc['scope']['border']}, size {nc['scope']['size']}, radius {nc['scope']['radius']}, "
           f"opacity {nc['scope']['opacity']}, colour {nc['scope']['color']}, font {nc['scope']['font']}, shadow 0), counting only the places that are converted now. "
           f"Instead of the 105 values / 357 places without a token that `ZUORDNUNG.md` proposed 1:1.",
           f"- With the **last wave** (wiki frontends `workbenches/view`, `widgets/plan`) put on the same scales instead of moving into styles: {sum(nc['with_last_wave'].values())} "
           f"(spacing {nc['with_last_wave']['spacing']}, size {nc['with_last_wave']['size']}, font {nc['with_last_wave']['font']}, radius {nc['with_last_wave']['radius']}, opacity {nc['with_last_wave']['opacity']}, "
           f"border {nc['with_last_wave']['border']}, colour {nc['with_last_wave']['color']}). They are not counted above because strategy rule 5 moves their values into styles.",
           f"- Variants (not the main result): size boxes may also sit on the space ladder and line widths: size {nc['size_shares_space_and_border']['size']} instead of {nc['scope']['size']} "
           f"(total {total - nc['scope']['size'] + nc['size_shares_space_and_border']['size']}); tolerance 4 px instead of 2: size {nc['tolerance_4']['size']} "
           f"(total {total - nc['scope']['size'] + nc['tolerance_4']['size']}).", "", "Where the 526 counted places go (columns: in scope now / last wave / style definition / drawn icon):", ""]
    kinds = Counter()
    rows = []
    for kind in sorted(data["counted"]):
        c = Counter()
        for e in lits:
            if e["kind"] == kind:
                c.update(e["classes"])
        rows.append([kind] + [c.get(k, 0) for k in CLASSES] + [data["counted"][kind]])
        kinds.update(c)
    rows.append(["**all**"] + [kinds.get(k, 0) for k in CLASSES] + [sum(data["counted"].values())])
    out += table(["kind", "scope", "last wave", "style definition", "icon", "counted"], rows) + [""]
    out += ["Style definition = `styles/craft_sheet.rs` (strategy 4, not a violation). Icon = `icon_kind.rs` and `icon_export.rs` (strategy 3, content). "
            f"Of the scope places, zero values (`size 0`: {zero('size')}, `border 0`: {zero('border')}) and `opacity 1.0` ({zero('opacity')}) need no token; the declaration is removed. The counter counts them too [offen: leave zero out of the counter].", "",
            "## 1. Rules used", "",
            "1. **Reference style Craft** (strategy 1): a literal is compared with the Craft value of a token (`styles/craft.rs`); the other four styles keep their own values.",
            "2. **A scale per kind**, read from the tokens that exist: `space.*`, `size.*` + `icon.size`, `font.size.*`, `radius.*`. Border width and opacity have no token yet: their scale is made only of new steps. Colours: exact equality with a Craft token or a drawing (no colour tolerance was given).",
            "3. **Fit.** A literal moves onto the nearest step when the deviation is at most **2 px** (opacity: 0.05, **[offen]** the strategy names no unit). Tie: the smaller step. A step is NEW only when no step fits; new steps are picked greedily: the literal that reaches the most still unplaced places, then the least total deviation, then the smaller value.",
            "4. **My addition (not in the strategy, [offen]): the deviation may also not exceed half of the smaller of the two values.** Without it a 1 px line could become 2 px (and `border` would need one token with all 92 hairlines doubled), or a 2 px padding 4 px. With it, 1 px stays near 1 px.",
            "5. **Not mapped now:** places in style definitions, drawn icons and the last wave (see section 0). Last-wave rows are still shown against the scale for information.", "",
            "## 2. The scales (value per style, Craft first; source = Craft definition line)", ""]
    for kind, title in (("spacing", "space"), ("size", "size (and icon.size)"), ("font", "font size"), ("radius", "radius"), ("border", "border width"), ("opacity", "opacity")):
        out += [f"**{title}** ({kind}, unit px{', 0..1' if kind == 'opacity' else ''})", ""]
        out += table(["token", *STYLES, "source (craft.rs line)"], scale_rows(data, kind)) or [""]
        out += [""]
    out += ["Other styles' values of NEW tokens are unknown: **[offen]** (decided when the style definitions get them; the Craft value is the literal, so Craft keeps its picture). "
            "Craft has square corners everywhere (`radius.* = 0`, test `the_sheet_has_no_rounded_corner`): no radius literal (4..16) fits a Craft step, see section 7, point 4. "
            "Craft defines no `border.*` and no `opacity.*` token (only the sheet literals `1px`, `0.4`); other styles define `border.focus.width` 2/3/4 (not a line width scale).", "",
            "## 3. New tokens (names after DTCG: group path, lower case; all names are proposals, role guessed from the places of use)", ""]
    new = [(k, n) for k in ("spacing", "border", "size", "radius", "opacity") for n in data["scales"][k]["new"]]
    rows = []
    for kind, n in new:
        cover = [e for e in lits if e["kind"] == kind and e.get("token") == [n["token"]] and e["classes"].get("scope")]
        rows.append([f"`{n['token']}`", kind, g(n["value"]), ", ".join(e["value"] for e in cover), sum(e["classes"]["scope"] for e in cover)])
    for c in data["new_colors"]:
        role = "tree panel background" if c["value"] == "#f7f7f8" else "line colour of the file manager"
        name = "color.surface.sidebar" if c["value"] == "#f7f7f8" else "color.border.subtle"
        rows.append([f"`{name}`", "colour", c["value"], f"{c['value']} ({role})", c["places"]])
    out += table(["token", "kind", "Craft value", "covers (literals in scope)", "scope places"], rows) + [""]
    out += [f"Colours: nearest Craft token by channel distance: " + ", ".join(f"`{c['value']}` is {c['distance']}/255 from `{c['nearest']}`" for c in data["new_colors"]) + ". Reason for NEW: no colour tolerance exists; mapping them to the role tokens `color.border.default` / `color.surface.panel` would be 5 to 25/255 off **[offen]**.", "",
            "Reason for each NEW dimension: no existing step within 2 px (and half of the smaller value). The large ones are specific layout measures (`size.dialog-max` 560, `size.col-s/-m` 96/120, `size.col-narrow` 72, `size.row-tall(er)` 56/60, `size.field-tall` 64). "
            "They are single uses: **[offen]** whether these stay tokens or become properties of a contract block; a coarser tolerance (4 px) merges 13 size steps to 8.", ""]
    out += ["## 4. Every counted literal and where it goes", "", "Places in brackets: scope / last wave / style definition / icon. `dev` = px (opacity: absolute) from the step.", ""]
    for kind in ("spacing", "size", "font", "radius", "border", "opacity", "color", "shadow"):
        groups = {}
        for e in lits:
            if e["kind"] == kind:
                cell = f"`{e['value']}` ({places(e)}{'; dev ' + g(e['dev']) if e.get('dev') else ''})"
                groups.setdefault(target(e), []).append(cell)
        out += [f"**{kind}**", ""] + table(["target", "literals (places; deviation)"], [[t, ", ".join(c)] for t, c in groups.items()]) + [""]
    out += ["## 5. Deviations in scope (literal != step), for the tolerance of the picture comparison", "",
            "Only places that are converted now. Full lists of places (also the last wave) are in `tokens.json` (`literals[].sites`). Every place listed here may differ by `dev` px in the Craft picture.", ""]
    rows = []
    for e in lits:
        sites = e.get("sites", {}).get("scope")
        if sites and e["kind"] != "color":
            rows.append([e["kind"], f"`{e['value']}`", f"`{e['token'][0]}` ({g(e['step'])})", g(e["dev"]), len(sites), "; ".join(s.replace("crates/fs-components-", "").replace("/src", "") for s in sites[:2]) + (" ..." if len(sites) > 2 else "")])
    out += table(["kind", "literal", "step", "dev", "places", "first places"], rows) + [""]
    lw = [e for e in lits if e.get("sites", {}).get("last-wave")]
    out += [f"Last wave: {sum(len(e['sites']['last-wave']) for e in lw)} further deviating places in {len(lw)} literals (largest: spacing 6 to 4 px: 19, spacing 10 to 8 px: 14, spacing 14 to 12 px: 9); they become style values instead, so no tolerance is needed.", ""]
    return out
